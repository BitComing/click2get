/**
 * 复制出去的文字：去掉完全空的行，内容与内容之间的换行照留。
 *
 * 正文里"空行"很多都是结构带来的，不是用户写出来的：
 * - 每个 captureBlock 是独立的块，块与块之间会被序列化成一个换行；
 * - 图片独占一行，文字节点前后也是空的；
 * - 手写回车留下的空段落。
 *
 * 这些行粘到别处就变成一串莫名其妙的空行（一个句子被撑成三段那么高）。
 * 复制是按"内容"走的，空行没有内容，直接丢掉；**有字的行之间的换行照留**，
 * 行内的硬换行（Shift+Enter）也不受影响 —— 那才是用户真的要的换行。
 *
 * 换行符不止 `\n`：网页翻译插件 / PDF / 老式 Windows 程序会给单独的 `\r`
 * 或者 U+2028/2029，按 `\n` 拆不开就会把几行粘成一行，所以统一认下面这一套。
 */

/** 换取行的写法：`\n`、`\r\n`、单独的 `\r`，以及 Unicode 的行 / 段分隔符。 */
const LINE_BREAK = /\r\n|[\r\n\u0085\u2028\u2029\u000b\u000c]/

export function cleanCopyText(raw: string): string {
  if (!raw) return ''
  return raw
    .split(LINE_BREAK)
    .filter((line) => line.trim() !== '')
    .join('\n')
}